// Renders docs/chaos.md from chaos/results/**/*.json. "Actual" values come only from result files.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT } from "./lib.js";

const ORDER = ["duplicate", "out-of-order", "missed-webhook", "tamper", "renewal-failure"];
const resultsDir = resolve(ROOT, "chaos/results");
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const ICON: Record<string, string> = { pass: "PASS", fail: "FAIL", precondition_violated: "PASS*" };

export function render(): string {
  const targets = existsSync(resultsDir) ? readdirSync(resultsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : [];
  const out: string[] = [
    "# Failure-injection results",
    "",
    "> Generated by `chaos/src/render.ts` from `chaos/results/**/*.json`. Do not edit by hand: re-run `chaos/run-all.sh`.",
    "",
  ];
  if (!targets.length) out.push("No results yet. Run `chaos/targets/nextjs.sh up && chaos/run-all.sh`.", "");
  for (const target of targets) {
    const files = readdirSync(resolve(resultsDir, target)).filter((f) => f.endsWith(".json"));
    const results = files.map((f) => JSON.parse(readFileSync(resolve(resultsDir, target, f), "utf8")));
    results.sort((a, b) => ORDER.indexOf(a.scenario) - ORDER.indexOf(b.scenario));
    out.push(`## Target: \`${target}\``, "", "| Scenario | Verdict | Delivery | Commit | Run |", "|---|---|---|---|---|");
    const historyPath = resolve(resultsDir, target, "history.jsonl");
    const history = existsSync(historyPath)
      ? readFileSync(historyPath, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l))
      : [];
    for (const r of results) out.push(`| ${esc(r.title)} | ${ICON[r.verdict] ?? r.verdict} | ${esc(r.delivery_mode)} | \`${r.git_sha}\` | ${r.finished_at} |`);
    out.push("");
    if (history.length) {
      out.push("Recorded runs (all runs in `history.jsonl`; the file was reset once during development, so earlier runs are not counted; the table above shows the latest):", "", "| Scenario | Runs | PASS | PASS* | FAIL |", "|---|---|---|---|---|");
      for (const r of results) {
        const h = history.filter((x) => x.scenario === r.scenario);
        const n = (v: string) => h.filter((x) => x.verdict === v).length;
        if (h.length) out.push(`| ${esc(r.title)} | ${h.length} | ${n("pass")} | ${n("precondition_violated")} | ${n("fail")} |`);
      }
      out.push("");
    }
    for (const r of results) {
      out.push(`### ${r.title}`, "", `Verdict: **${ICON[r.verdict] ?? r.verdict}**`, "");
      if (r.precondition_note) out.push(`> \`PASS*\`: ${esc(r.precondition_note)}`, "");
      out.push("| Check | Expected | Actual | |", "|---|---|---|---|");
      for (const a of r.assertions) out.push(`| \`${a.id}\` | ${esc(a.expected)} | ${esc(a.actual)} | ${a.pass ? "PASS" : "FAIL"} |`);
      out.push("");
    }
  }
  return out.join("\n");
}

const target = resolve(ROOT, "docs/chaos.md");
const text = render();
if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== text) { console.error("docs/chaos.md is out of date: run chaos/run-all.sh (or chaos/src/render.ts)"); process.exit(1); }
  console.log("docs/chaos.md is up to date");
} else {
  writeFileSync(target, text);
  console.log("wrote docs/chaos.md");
}
